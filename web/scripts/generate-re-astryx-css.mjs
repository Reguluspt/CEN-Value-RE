import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import {
  assertReAstryxCssContained,
  scopeReAstryxVendorCss,
} from './scope-re-astryx-css.mjs';

const require = createRequire(import.meta.url);
const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const webRoot = path.resolve(scriptDir, '..');
const outputDir = path.join(webRoot, 'src', 're', 'generated');

const sources = [
  {
    specifier: '@astryxdesign/core/astryx.css',
    output: 'astryx-core.scoped.css',
  },
  {
    specifier: '@astryxdesign/theme-neutral/theme.css',
    output: 'neutral-theme.scoped.css',
  },
];

fs.mkdirSync(outputDir, { recursive: true });

for (const source of sources) {
  const resolved = require.resolve(source.specifier);
  const raw = fs.readFileSync(resolved, 'utf8');
  const transformed = scopeReAstryxVendorCss(raw, resolved);
  assertReAstryxCssContained(transformed, source.specifier);

  const banner = [
    '/* AUTO-GENERATED by scripts/generate-re-astryx-css.mjs.',
    ` * Source: ${source.specifier}`,
    ' * Do not edit; global Astryx token selectors are rewritten to .cenvalue-re-surface.',
    ' */',
    '',
  ].join('\n');

  fs.writeFileSync(path.join(outputDir, source.output), banner + transformed, 'utf8');
}

console.log('E0-PR-002 scoped Astryx CSS generated');
console.log(`- ${path.relative(webRoot, outputDir)}/astryx-core.scoped.css`);
console.log(`- ${path.relative(webRoot, outputDir)}/neutral-theme.scoped.css`);
